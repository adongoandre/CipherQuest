"""Attempt and Progress models.

Attempt records what happened at each stage of a mission. Progress stores the
player's durable outcome per mission.

Idempotency: an attempt may carry an ``idempotency_key`` generated by the
client. Replaying the same key returns the original stored result instead of
computing a second reward. ``Progress.xp_awarded`` is granted exactly once, on
first completion, so duplicate or repeated correct submissions cannot multiply
rewards.
"""

from __future__ import annotations

import enum
from datetime import datetime

from sqlalchemy import (
    Boolean,
    DateTime,
    Enum,
    ForeignKey,
    Integer,
    String,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base


class AttemptStage(str, enum.Enum):
    RIDDLE = "riddle"
    KEY_REVEAL = "key_reveal"
    CONTEXT_CLUE = "context_clue"
    DECRYPT = "decrypt"
    EXPLANATION = "explanation"
    # HINT is deliberately outside the progression ladder: recording a hint
    # request must never unlock a later stage.
    HINT = "hint"


class AttemptOutcome(str, enum.Enum):
    CORRECT = "correct"
    INCORRECT = "incorrect"
    HINT_REQUESTED = "hint_requested"
    REVEALED = "revealed"


class Attempt(Base):
    __tablename__ = "attempts"
    __table_args__ = (
        UniqueConstraint("session_id", "idempotency_key", name="uq_attempt_idempotency"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[int] = mapped_column(
        ForeignKey("player_sessions.id", ondelete="CASCADE"), nullable=False, index=True
    )
    mission_id: Mapped[int] = mapped_column(
        ForeignKey("missions.id", ondelete="CASCADE"), nullable=False, index=True
    )
    stage: Mapped[AttemptStage] = mapped_column(
        Enum(AttemptStage, name="attempt_stage"), nullable=False
    )
    outcome: Mapped[AttemptOutcome] = mapped_column(
        Enum(AttemptOutcome, name="attempt_outcome"), nullable=False
    )
    hints_used: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    elapsed_seconds: Mapped[int | None] = mapped_column(Integer, nullable=True)
    score: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    idempotency_key: Mapped[str | None] = mapped_column(String(64), nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )




class Progress(Base):
    __tablename__ = "progress"
    __table_args__ = (UniqueConstraint("session_id", "mission_id", name="uq_progress_pair"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[int] = mapped_column(
        ForeignKey("player_sessions.id", ondelete="CASCADE"), nullable=False, index=True
    )
    mission_id: Mapped[int] = mapped_column(
        ForeignKey("missions.id", ondelete="CASCADE"), nullable=False, index=True
    )

    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    # Which telling of the mission this session is currently playing.
    # 0 = the original story; replaying a completed mission advances it.
    story_index: Mapped[int] = mapped_column(Integer, nullable=False, default=0, server_default="0")
    best_score: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    completion_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    xp_awarded: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    hints_used_best: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    comprehension_awarded: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )
